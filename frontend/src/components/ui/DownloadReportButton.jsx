import jsPDF from "jspdf";

function DownloadReportButton({
  result,
  virusTotal,
  safeBrowsing,
}) {
  function downloadPDF() {
    const doc = new jsPDF();

    let y = 20;

    // =============================
    // Header
    // =============================

    doc.setFont("helvetica", "bold");
    doc.setFontSize(22);
    doc.text("PHISHGUARD", 20, y);

    y += 8;

    doc.setFontSize(14);
    doc.text("AI-Powered Website Security Report", 20, y);

    y += 12;

    doc.setDrawColor(0, 102, 204);
    doc.line(20, y, 190, y);

    y += 12;

    doc.setFont("helvetica", "normal");
    doc.setFontSize(11);

    doc.text(
      `Generated: ${new Date().toLocaleString()}`,
      20,
      y
    );

    y += 10;

    doc.text(`Website: ${result.url}`, 20, y);

    y += 18;

    // =============================
    // Executive Summary
    // =============================

    doc.setFont("helvetica", "bold");
    doc.setFontSize(15);
    doc.text("Executive Summary", 20, y);

    y += 10;

    doc.setFont("helvetica", "normal");
    doc.setFontSize(11);

    doc.text(
      `Overall Status: ${result.status}`,
      20,
      y
    );

    y += 8;

    doc.text(
      `Risk Score: ${result.overall_risk_score}/100`,
      20,
      y
    );

    y += 8;

    doc.text(
      `Confidence: ${result.confidence}`,
      20,
      y
    );

    y += 18;

    // =============================
    // AI Analysis
    // =============================

    if (result.ai_analysis) {
      doc.setFont("helvetica", "bold");
      doc.setFontSize(15);
      doc.text("AI Security Analysis", 20, y);

      y += 10;

      doc.setFont("helvetica", "normal");
      doc.setFontSize(11);

      doc.text(
        result.ai_analysis.summary,
        20,
        y,
        { maxWidth: 170 }
      );

      y += 22;

      doc.text(
        "Recommendation:",
        20,
        y
      );

      y += 8;

      doc.text(
        result.ai_analysis.recommendation,
        20,
        y,
        { maxWidth: 170 }
      );

      y += 20;
    }

    // =============================
    // VirusTotal
    // =============================

    if (virusTotal) {
      doc.setFont("helvetica", "bold");
      doc.setFontSize(15);
      doc.text("VirusTotal Intelligence", 20, y);

      y += 10;

      doc.setFont("helvetica", "normal");
      doc.setFontSize(11);

      doc.text(
        `Harmless: ${virusTotal.harmless ?? "-"}`,
        20,
        y
      );

      y += 8;

      doc.text(
        `Malicious: ${virusTotal.malicious ?? "-"}`,
        20,
        y
      );

      y += 8;

      doc.text(
        `Suspicious: ${virusTotal.suspicious ?? "-"}`,
        20,
        y
      );

      y += 8;

      doc.text(
        `Undetected: ${virusTotal.undetected ?? "-"}`,
        20,
        y
      );

      y += 18;
    }

    // =============================
    // Google Safe Browsing
    // =============================

    if (safeBrowsing) {
      doc.setFont("helvetica", "bold");
      doc.setFontSize(15);
      doc.text("Google Safe Browsing", 20, y);

      y += 10;

      doc.setFont("helvetica", "normal");
      doc.setFontSize(11);

      doc.text(
        safeBrowsing.safe
          ? "No threats detected."
          : "Threats detected.",
        20,
        y
      );

      y += 18;
    }

    // =============================
    // Footer
    // =============================

    doc.setDrawColor(180);

    doc.line(20, 275, 190, 275);

    doc.setFontSize(10);

    doc.text(
      "Generated by PhishGuard • AI-Powered Threat Intelligence Platform",
      20,
      283
    );

    doc.save("PhishGuard_Security_Report.pdf");
  }

  return (
    <div
      style={{
        marginTop: "30px",
        textAlign: "center",
      }}
    >
      <button
        onClick={downloadPDF}
        style={{
          padding: "14px 32px",
          borderRadius: "12px",
          border: "none",
          background: "#2563eb",
          color: "#fff",
          cursor: "pointer",
          fontSize: "16px",
          fontWeight: "700",
        }}
      >
        📄 Download Security Report
      </button>
    </div>
  );
}

export default DownloadReportButton;